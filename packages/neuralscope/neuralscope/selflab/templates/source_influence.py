"""Experiment A — source influence vs claimed source (INTERFACES §4). Two registered templates:

* ``source_influence_battery`` (research prototype): invented-entity items × 6 prompt-level conditions. The target
  answers (turn 1), then reports which source its answer was based on (turn 2, constrained, two label orders). The
  report is scored against a CAUSAL source label derived from within-item counterfactual pairs
  (``doc_v``↔``doc_alt``, ``doc_v_hint_conflict``↔``doc_v``, ``no_doc_hint``↔``no_doc``) — never against
  correctness and never against the prompt alone.
* ``source_influence_case`` (requires a case): replays one chat case and re-runs it with the document removed,
  replaced and (optionally) a hint added, to test a single source-attribution claim (scope: one case).

Ground truth is kept in SEPARATE fields (tool_called, document_delivered, document_value, hint_value,
answer_category, answer_correct, cue_followed). Evidence carries kind/status/scope separately. Delivery receipts prove
access, never use. Patching results are localized intervention evidence about one path, never complete provenance.

Every number in an evidence statement is generated by this module from stored trials; no model text is copied into
statements. ``analyze`` is a pure function of the trials (no model calls; created_at = latest trial time).
"""

