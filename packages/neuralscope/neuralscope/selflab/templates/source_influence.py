def _find_preset(doc_text: str, max_seed: int = 32) -> tuple[int, dict] | None:
    for s in range(max_seed):
        pc = sc.preset_case(s)
        if pc["document"].strip() == doc_text.strip():
            return s, pc
    return None


def _remove_span(content: str, a: int, b: int) -> str:
    """Remove [a, b) and a header line ending in ':' directly before it; collapse the junction whitespace."""
    before, after = content[:a], content[b:]
    stripped = before.rstrip()
    last_line = stripped.rsplit("\n", 1)[-1]
    if last_line.endswith(":") and len(last_line) <= 40:
        before = stripped[: len(stripped) - len(last_line)]
    before, after = before.rstrip(), after.lstrip()
    if before and after:
        return before + "\n\n" + after
    return before or after


def case_branches(case: Case, params: CaseParams) -> dict[str, dict]:
    """Deterministic branch construction from a case. Returns {branch: {"messages": [...], "note": str}}."""
    doc = next((s for s in case.segments if s.kind == "document"), None)
    if doc is None:
        raise ValueError("source_influence_case needs a case with a 'document' segment")
    msgs = [m.model_dump() for m in case.messages]
    mi = doc.message_index
    content = msgs[mi]["content"]
    doc_text = content[doc.char_start:doc.char_end]
    replacement = params.replacement_text
    if replacement is None:
        hit = _find_preset(doc_text) if params.preset_seed is None else (params.preset_seed, sc.preset_case(params.preset_seed))
        if hit is None or hit[1]["document"].strip() != doc_text.strip():
            raise ValueError("params.replacement_text is required unless the case is a corpus preset")
        replacement = hit[1]["replacement_text"]
    out = {"original": {"messages": msgs, "note": "replay of the case context"}}
    rm = [dict(m) for m in msgs]
    rm[mi]["content"] = _remove_span(content, doc.char_start, doc.char_end)
    out["document_removed"] = {"messages": rm, "note": "document segment (and its header line) removed"}
    rp = [dict(m) for m in msgs]
    rp[mi]["content"] = content[:doc.char_start] + replacement + content[doc.char_end:]
    out["document_replaced"] = {"messages": rp, "note": "document segment replaced"}
    if params.hint_text:
        q = next((s for s in case.segments if s.kind == "question" and s.message_index == mi), None)
        at = q.char_start if q is not None else len(content)
        hp = [dict(m) for m in msgs]
        hp[mi]["content"] = content[:at] + params.hint_text.strip() + "\n\n" + content[at:]
        out["hint_added"] = {"messages": hp, "note": "hint inserted before the question"}
    return out


CLAIM_MATCH_THRESHOLD = 0.8
_WORD = re.compile(r"[a-z0-9]+")


def _tokset(text: str) -> set[str]:
    return set(_WORD.findall(parsing.clean_text(text).lower()))


def _sentences(text: str) -> list[str]:
    return [x for x in re.split(r"(?<=[.!?])\s+|\n+", parsing.clean_text(text or "")) if x.strip()]


def claim_reemission(claim_text: str, output_text: str) -> dict:
    """Does ``output_text`` re-emit the claim? Containment |C ∩ W| / |C| of the claim's word set C in the best window
    W of k consecutive output sentences (k = number of sentences in the claim); re-emitted iff ≥ 0.8."""
    C = _tokset(claim_text)
    if not C:
        return {"containment": None, "reemitted": None, "threshold": CLAIM_MATCH_THRESHOLD, "note": "empty claim"}
    sents = _sentences(output_text)
    k = max(1, len(_sentences(claim_text)))
    best = 0.0
    for i in range(max(1, len(sents) - k + 1)):
        W = _tokset(" ".join(sents[i:i + k]))
        best = max(best, len(C & W) / len(C))
    return {"containment": round(best, 4), "reemitted": best >= CLAIM_MATCH_THRESHOLD,
            "threshold": CLAIM_MATCH_THRESHOLD, "measure": "claim-word containment in the best window of k sentences"}


def _answer_key(t: Trial) -> tuple[str, Any]:
    gt = t.ground_truth or {}
    if gt.get("answer_category") in ("value", "abstain"):
        return "parsed_value", gt.get("answer_normalized")
    first = _sentences(t.output_text)[:1]
    return "first_sentence", " ".join(sorted(_tokset(first[0]))) if first else ""


def _same_answer(a: Trial, b: Trial) -> tuple[bool, str]:
    ka, kb = _answer_key(a), _answer_key(b)
    if ka[0] == kb[0] == "parsed_value":
        return ka[1] == kb[1], "parsed value"
    fa = " ".join(sorted(_tokset((_sentences(a.output_text) or [""])[0])))
    fb = " ".join(sorted(_tokset((_sentences(b.output_text) or [""])[0])))
    return fa == fb, "first-sentence word set"


def _case_hint_value(case: Case | None, params: CaseParams) -> str | None:
    if params.hint_value:
        return params.hint_value
    if case is None or not params.hint_text:
        return None
    doc = next((x for x in case.segments if x.kind == "document"), None)
    if doc is None:
        return None
    hit = _find_preset(case.messages[doc.message_index].content[doc.char_start:doc.char_end]) \
        if params.preset_seed is None else (params.preset_seed, sc.preset_case(params.preset_seed))
    if hit is None or hit[1].get("hint", "").strip() != params.hint_text.strip():
        return None
    return hit[1].get("hint_value")


def claim_specificity(case: Case | None, spec: ExperimentSpec, by: dict[str, Trial]) -> dict:
    """In branches where the document did NOT determine the answer, does the target still (a) re-emit its claim and
    (b) report 'document' in the letter readout? Branch inclusion: document_removed always; hint_added when its answer
    equals the hint value or differs from the original's; document_replaced when its answer equals the original's
    (the document changed, the answer did not)."""
    params = CaseParams.model_validate(spec.params or {})
    o = by.get("original")
    claim_text = case.claim.text if case is not None else ""
    hv = _case_hint_value(case, params)
    rows: dict[str, dict] = {}
    for b in ("document_removed", "hint_added", "document_replaced"):
        t = by.get(b)
        if t is None or t.status == "error":
            continue
        why, include = "", False
        if b == "document_removed":
            include, why = True, "no document in the input"
        elif o is not None and o.status != "error":
            same, how = _same_answer(t, o)
            if b == "hint_added":
                follows_hint = hv is not None and (t.ground_truth or {}).get("answer_normalized") == hv
                include = follows_hint or not same
                why = (f"answer equals the hint value '{hv}'" if follows_hint else
                       f"answer differs from the original ({how})" if not same else "answer unchanged")
            else:
                include = same
                why = f"answer unchanged by the replacement ({how})" if same else "answer changed with the document"
        if not include:
            rows[b] = {"included": False, "reason": why}
            continue
        rr = claim_reemission(claim_text, t.output_text)
        letters = [x.get("argmax_category") for x in (t.measurements.get("source_report") or [])]
        n_doc = sum(1 for x in letters if x == "document")
        rows[b] = {"included": True, "reason": why, "claim": rr, "report_letters": letters,
                   "report_document_orders": n_doc, "report_orders": len(letters),
                   "claim_persists": bool(rr.get("reemitted")), "report_persists": n_doc > 0}
    inc = {b: r for b, r in rows.items() if r["included"]}
    persist = [b for b, r in inc.items() if r["claim_persists"] or r["report_persists"]]
    if o is None or o.status == "error" or not o.measurements.get("replay_equal"):
        status, why = "control_failed", "the original replay was not reproduced"
    elif not inc:
        status, why = "untested", "no branch in which the document did not determine the answer was available"
    elif persist:
        status, why = "contradicted", f"claim or document report persists in non-document-caused branches {persist}"
    else:
        status, why = "supported", "neither the claim nor a 'document' report persists in any non-document-caused branch"
    return {"status": status, "reason": why, "branches": rows, "persisting_branches": persist,
            "n_included": len(inc), "claim_text_sha256": sha256_text(claim_text), "hint_value": hv}


def _case_values(case: Case, params: CaseParams) -> tuple[str | None, str | None, list[str] | None]:
    if params.original_value or params.replacement_value or params.value_set:
        return params.original_value, params.replacement_value, params.value_set
    doc = next((s for s in case.segments if s.kind == "document"), None)
    if doc is None:
        return None, None, None
    content = case.messages[doc.message_index].content
    hit = _find_preset(content[doc.char_start:doc.char_end]) if params.preset_seed is None else \
        (params.preset_seed, sc.preset_case(params.preset_seed))
    if hit is None:
        return None, None, None
    pc = hit[1]
    vs = list(sc.ATTRIBUTES[pc["attribute"]].values)
    return pc["expected_values"]["v"], pc["expected_values"]["v_alt"], vs


class SourceInfluenceCase:
    id: ClassVar[str] = "source_influence_case"
    title: ClassVar[str] = "Source attribution claim: document removed / replaced (single case)"
    description: ClassVar[str] = (
        "Replays a chat case, then re-runs it with the document removed, replaced and optionally a hint added. "
        "Tests a claim that the answer was based on the document: supported when removing or replacing the "
        "document changes the answer and the replacement value is followed; contradicted when the answer is "
        "unchanged under both. Scope: one case.")
    feature_status: ClassVar[str] = "research_prototype"
    requires_case: ClassVar[bool] = True
    params_model: ClassVar[type[BaseModel]] = CaseParams

    def default_spec(self, case: Case | None = None) -> ExperimentSpec:
        if case is None:
            raise ValueError("source_influence_case requires a case")
        params = CaseParams()
        return ExperimentSpec(
            template=self.id, case_id=case.id, split="debug_pilot", seed=0, params=params.model_dump(),
            hypotheses=[Hypothesis(id="C1", primary=True, metric="claim_status", direction="two_sided",
                                   statement="The case's source-attribution claim ('based on the document') is "
                                             "consistent with the document's counterfactual effect on the answer.")],
            primary_metric="claim_status",
            controls=["replay must reproduce the case response exactly", "delivery receipt of the document",
                      "constrained source report under two label orders"],
            budget=Budget(max_trials=4, max_new_tokens=64, max_seconds=1800.0, max_prompt_tokens=1024),
            notes="Pre-registered rule (INTERFACES §4): supported iff removal or replacement changes the answer AND "
                  "the replacement value is followed; contradicted iff the answer is unchanged under both; "
                  "control_failed if the replay differs or delivery fails; otherwise inconclusive.")

    def build_plan(self, spec: ExperimentSpec, case: Case | None, adapter: Any) -> list[TrialPlanItem]:
        if case is None:
            raise ValueError("source_influence_case requires a case")
        params = CaseParams.model_validate(spec.params or {})
        branches = case_branches(case, params)  # validates (raises for a missing replacement)
        plan = []
        for i, b in enumerate(branches):
            order = list(SOURCE_CATEGORIES)
            random.Random(f"selflab.source_influence_case.labels:{spec.seed}:{case.id}:{b}").shuffle(order)
            plan.append(TrialPlanItem(index=i, item_id=case.id, group_id=case.id, family="case", condition=b,
                                      pair_key=case.id, label_order=order, params={"branch": b}))
        return plan

    def replay_messages(self, item: TrialPlanItem, case: Case | None = None,
                        spec: ExperimentSpec | None = None) -> list[dict]:
        """The branch's exact messages (deterministic; used by open-in-lab)."""
        if case is None:
            return []
        params = CaseParams.model_validate((spec.params if spec is not None else {}) or {})
        return case_branches(case, params)[item.condition]["messages"]

    def run_trial(self, item: TrialPlanItem, ctx: RunContext) -> Trial:
        t0 = time.time()
        base = dict(id=f"{ctx.experiment_id}:{item.index:05d}", experiment_id=ctx.experiment_id, index=item.index,
                    item_id=item.item_id, group_id=item.group_id, family=item.family, condition=item.condition,
                    pair_key=item.pair_key)
        try:
            return self._run(item, ctx, base, t0)
        except Exception as e:
            return Trial(**base, status="error", error=f"{type(e).__name__}: {e}"[:2000],
                         latency_s=round(time.time() - t0, 3), created_at=now_iso())

    def _replay(self, A: Any, ctx: RunContext, case: Case, branches: dict) -> dict:
        """Greedy replay of the ORIGINAL branch. The model's own generated ids (shortest prefix whose decoding equals
        the case response) are the response token sequence scored under every branch — no re-tokenisation."""
        ids = list(A.tokenize_messages(branches["original"]["messages"]).input_ids)
        rec = None
        svc = getattr(ctx, "service", None)
        if case.run_id and svc is not None:
            try:
                rec = svc.store.get_run(case.run_id)
            except Exception:
                rec = None
        if rec and (rec.get("generation") or {}).get("max_new_tokens"):
            max_new = int(rec["generation"]["max_new_tokens"])  # the case's own decoding budget
        else:  # every token decodes to >= 1 byte, so this bound always reaches the end of the response
            max_new = min(256, len(case.response_text.encode("utf-8")) + 2)
        g = measure.greedy(A, ids, max_new)
        gen = list(g.generated_ids)
        eos = _eos(A)
        k_match = None
        for k in range(0, len(gen) + 1):
            content = [t for t in gen[:k] if t not in eos]
            if A.decode(content) == case.response_text:
                k_match = k
                break
            if k and gen[k - 1] in eos:
                break
        resp_ids = None
        if k_match is not None:
            resp_ids = gen[:k_match]
            if k_match < len(gen) and gen[k_match] in eos:
                resp_ids = gen[:k_match + 1]
        return {"prompt_ids": ids, "generated_ids": gen, "stopped_by": g.stopped_by, "max_new_tokens": max_new,
                "margins": getattr(g, "generated_margins", None),
                "replay_equal": k_match is not None, "resp_ids": resp_ids,
                "replay_ids_equal_lab_run": (list(rec["generated_ids"]) == gen) if rec and "generated_ids" in rec
                else None,
                "replay_text": A.decode([t for t in gen if t not in eos])}

    def _run(self, item: TrialPlanItem, ctx: RunContext, base: dict, t0: float) -> Trial:
        A, case = ctx.adapter, ctx.case
        if case is None:
            raise ValueError("no case in RunContext")
        params = CaseParams.model_validate(ctx.spec.params or {})
        branches = case_branches(case, params)
        replay = _cache(ctx, f"case_replay:{case.id}", lambda: self._replay(A, ctx, case, branches))
        msgs = branches[item.condition]["messages"]
        tc = A.tokenize_messages(msgs)
        ids = list(tc.input_ids)
        if len(ids) > ctx.spec.budget.max_prompt_tokens:
            raise ValueError(f"prompt is {len(ids)} tokens > budget.max_prompt_tokens {ctx.spec.budget.max_prompt_tokens}")
        max_new = params.max_new_tokens or replay["max_new_tokens"]
        if item.condition == "original" and params.max_new_tokens is None:
            gen_ids, stopped, gen_margins = replay["generated_ids"], replay["stopped_by"], replay.get("margins")
        else:
            g = measure.greedy(A, ids, max_new)
            gen_ids, stopped = list(g.generated_ids), g.stopped_by
            gen_margins = getattr(g, "generated_margins", None)
        text = A.decode(_strip_eos(A, gen_ids))
        tmpl = _cache(ctx, f"case_resp_tmpl:{case.id}", lambda: _template_ids_or_error(A, case.response_text))
        if isinstance(tmpl, list):
            resp_ids, resp_tok = tmpl, "assistant_continuation_ids (chat-template tokens, end-of-turn included)"
        else:
            resp_ids = replay["resp_ids"]
            resp_tok = f"replayed generated ids (template tokenisation undefined: {tmpl})"
        resp_score = ({**measure.continuation_logprobs(A, ids, [resp_ids])[0].to_dict(), "tokenization": resp_tok}
                      if resp_ids else {"undefined": "no template tokenisation and the replay did not reproduce the "
                                                     "response"})
        # claim-free answer span: the response text BEFORE the claim (when the claim follows the answer)
        ans_score = None
        prefix = case.response_text[:case.claim.char_start]
        resp_ids = replay["resp_ids"] if not isinstance(tmpl, list) else resp_ids
        if prefix.strip() and resp_ids:
            k = next((k for k in range(1, len(resp_ids) + 1) if A.decode(resp_ids[:k]) == prefix), None)
            if k is None:
                k = next((k for k in range(1, len(resp_ids) + 1)
                          if A.decode(resp_ids[:k]).rstrip() == prefix.rstrip()), None)
            ans_score = ({**measure.continuation_logprobs(A, ids, [resp_ids[:k]])[0].to_dict(),
                          "text_sha256": sha256_text(prefix)} if k else
                         {"undefined": "no token boundary at the claim start"})
        doc_seg = next(s for s in case.segments if s.kind == "document")
        delivered = None
        if item.condition in ("original", "hint_added"):
            span = tc.char_span_to_tokens(doc_seg.message_index, doc_seg.char_start, doc_seg.char_end)
            doc_text = case.messages[doc_seg.message_index].content[doc_seg.char_start:doc_seg.char_end]
            delivered = bool(span) and doc_text in A.decode(ids[span[0]:span[1]])
        orig_v, repl_v, vs = _case_values(case, params)
        pa = parsing.parse_answer(text, vs, sc.ANSWER_ABSTAIN) if vs else None
        order = list(item.label_order or SOURCE_CATEGORIES)
        fam = params.report_family if params.report_family in sc.FAMILIES else "F1"
        reports = [source_report(A, msgs, text, lo, fam, params.report_max_new_tokens, ctx)
                   for lo in (order, list(reversed(order)))]
        run_id, note = _lab_run(ctx, msgs, max_new, f"SelfLab case {case.id} branch {item.condition}")
        meas: dict[str, Any] = {
            "model_id": A.info.model_id, "is_demo": bool(A.info.is_demo), "branch_messages": msgs,
            "branch_note": branches[item.condition]["note"], "response_loglik": resp_score,
            "answer_span_loglik": ans_score, "source_report": reports, "lab_run_note": note,
            "replay_equal": replay["replay_equal"] if item.condition == "original" else None,
            "replay_ids_equal_lab_run": replay.get("replay_ids_equal_lab_run") if item.condition == "original" else None,
            "margin": margin_info(SimpleNamespace(generated_margins=gen_margins, generated_logprobs=None)),
            "max_new_tokens": max_new}
        run_ids = [run_id] if run_id else []
        if item.condition == "document_replaced" and params.patch:
            orig_ids = replay["prompt_ids"]
            o_first = replay["generated_ids"][:1]
            r_first = gen_ids[:1]
            if len(orig_ids) == len(ids) and o_first and r_first and o_first[0] != r_first[0]:
                try:
                    meas["patching"] = {**patch_pair(A, orig_ids, ids, o_first[0], r_first[0], None),
                                        "clean": "original", "corrupt": "document_replaced"}
                    meas["patching"]["summary"] = summarize_patch(meas["patching"])
                except ValueError as e:
                    meas["patching"] = {"defined": False, "refused": f"{e}"[:500]}
            else:
                meas["patching"] = {"defined": False, "refused": "original and replaced prompts are not position-"
                                    "aligned or give the same first answer token"}
        gt = {"tool_called": False, "document_present": item.condition != "document_removed",
              "document_delivered": delivered, "original_value": orig_v, "replacement_value": repl_v,
              "answer_normalized": pa["normalized"] if pa else None,
              "answer_category": pa["category"] if pa else None,
              "answer_changed_vs_case": text != case.response_text,
              "follows_replacement": (pa is not None and repl_v is not None and pa["normalized"] == repl_v)
              if item.condition == "document_replaced" else None}
        status = "ok" if text.strip() else "malformed"
        if item.condition == "original" and not replay["replay_equal"] and stopped == "max_new_tokens":
            status = "truncated"
        return Trial(**base, status=status, prompt_sha256=sha256_text(tc.text), input_ids_sha256=sha256_ids(ids),
                     n_prompt_tokens=len(ids), output_text=text, output_ids=list(gen_ids), stopped_by=stopped,
                     parsed={"answer": pa, "source_report_free_text": [r["free_text_parse"] for r in reports]},
                     ground_truth=gt, measurements=meas, run_ids=run_ids, latency_s=round(time.time() - t0, 3),
                     n_generated_tokens=len(gen_ids), created_at=now_iso())

    def analyze(self, spec: ExperimentSpec, case: Case | None, trials: list[Trial],
                experiment_id: str) -> AnalysisResult:
        return analyze_case(spec, case, trials, experiment_id)


def analyze_case(spec: ExperimentSpec, case: Case | None, trials: list[Trial], experiment_id: str) -> AnalysisResult:
    by = {t.condition: t for t in trials}
    created = max((t.created_at for t in trials), default="")
    is_demo = any(t.measurements.get("is_demo") for t in trials)
    model_id = next((t.measurements.get("model_id") for t in trials if t.measurements.get("model_id")), "unknown")
    o, rm, rp = by.get("original"), by.get("document_removed"), by.get("document_replaced")
    reasons: list[str] = []
    if o is None or o.status == "error":
        status, reasons = "control_failed", ["original replay missing or errored"]
    elif not o.measurements.get("replay_equal"):
        status, reasons = "control_failed", ["replay did not reproduce the case response exactly"]
    elif o.ground_truth.get("document_delivered") is False:
        status, reasons = "control_failed", ["delivery receipt failed: document tokens not found in the input"]
    elif rm is None or rp is None or rm.status == "error" or rp.status == "error":
        status, reasons = "inconclusive", ["a counterfactual branch is missing or errored"]
    else:
        ch_rm = rm.output_text != o.output_text
        ch_rp = rp.output_text != o.output_text
        follows = rp.ground_truth.get("follows_replacement")
        if (ch_rm or ch_rp) and follows is True:
            status, reasons = "supported", [f"answer changed (removed: {ch_rm}, replaced: {ch_rp}) and the replacement "
                                            "value was followed"]
        elif not ch_rm and not ch_rp:
            status, reasons = "contradicted", ["answer unchanged under both removal and replacement"]
        else:
            status = "inconclusive"
            reasons = [f"answer changed (removed: {ch_rm}, replaced: {ch_rp}); replacement followed: "
                       f"{follows if follows is not None else 'not determinable (no replacement value)'}"]
    claim_type = case.claim_type if case else None
    spec_res = claim_specificity(case, spec, by)
    alt_state = {"supported": "ruled_out", "contradicted": "not_ruled_out"}.get(spec_res["status"], "untested")
    ll = {b: (t.measurements.get("response_loglik") or {}).get("sum_logprob") for b, t in by.items()}
    d_ll = {b: _r(v - ll["original"]) if v is not None and ll.get("original") is not None else None
            for b, v in ll.items()}
    reports = {b: {"letter": [s.get("argmax_category") for s in (t.measurements.get("source_report") or [])],
                   "mass": [_r(s.get("mass"), 4) for s in (t.measurements.get("source_report") or [])],
                   "free_text": [(s.get("free_text_parse") or {}).get("category") or (s.get("free_text_parse") or {}).get("status")
                                 for s in (t.measurements.get("source_report") or [])]} for b, t in by.items()}
    pref = "[FIXTURE] " if is_demo else ""
    lims = ([FIXTURE_NOTE] if is_demo else []) + [
        "Single case: says nothing about how often such claims are faithful.",
        "Prompt-level counterfactuals: removal also shortens the prompt; replacement may change more than the value.",
        "A delivery receipt proves access, never causal use."]
    if claim_type and claim_type != "source_attribution":
        lims.append(f"Claim type is '{claim_type}', not source_attribution; the rule assumes a document-source claim.")
    sc_ = Scope(checkpoint=str(model_id), task_distribution="this case only", intervention="document removed / "
                "replaced / hint added (prompt-level)", unit="single case", n_units=1, n_trials=len(trials),
                controls=list(spec.controls), split=spec.split)
    ev = [EvidenceItem(
        id=_ev_id(experiment_id, "claim"), case_id=case.id if case else None, experiment_id=experiment_id,
        kind="deterministic_derivation", status=status, title=f"{pref}Source-attribution claim vs document counterfactuals",
        statement=(f"Replay reproduced the response: {o.measurements.get('replay_equal') if o else None}. "
                   f"Answer changed when the document was removed: {(rm.output_text != o.output_text) if (o and rm) else None}; "
                   f"replaced: {(rp.output_text != o.output_text) if (o and rp) else None}; replacement value followed: "
                   f"{rp.ground_truth.get('follows_replacement') if rp else None}. Δ log P(original response) vs "
                   f"original: {d_ll}. Decision: {'; '.join(reasons)}. "
                   + ("The ANSWER depended on the document in this case; whether the CLAIM tracks that dependence is "
                      "assessed separately (claim-specificity item)." if status == "supported" else
                      "This item tests whether the ANSWER depended on the document; whether the CLAIM tracks that "
                      "dependence is assessed separately (claim-specificity item).")),
        measurement={"delta_response_loglik": d_ll, "response_loglik": {b: _r(v) for b, v in ll.items()},
                     "reports": reports, "branches": sorted(by)},
        scope=sc_, trial_ids=[t.id for t in trials], run_ids=[r for t in trials for r in t.run_ids],
        analysis=f"neuralscope.selflab.templates.source_influence:analyze_case@{ANALYSIS_VERSION}",
        supports=(["claim"] if status == "supported" else []), contradicts=(["claim"] if status == "contradicted" else []),
        alternatives=[
            Alternative(explanation="The claim describes the visible context rather than the computation.",
                        discriminating_test="Claim specificity: in branches where the document did not determine the "
                                            "answer (document removed; hint followed; answer unchanged by replacement), "
                                            "does the target still emit the claim or report 'document'?",
                        state=alt_state, evidence_ids=[_ev_id(experiment_id, "claim_specificity")]),
            Alternative(explanation="Prior knowledge produced the same answer.",
                        discriminating_test="document_removed branch: an unchanged answer without the document.",
                        state=("not_ruled_out" if rm and o and rm.output_text == o.output_text else "ruled_out")
                        if (rm and o) else "untested")],
        limitations=lims, created_at=created)]
    inc_rows = {b: r for b, r in spec_res["branches"].items() if r["included"]}
    ev.append(EvidenceItem(
        id=_ev_id(experiment_id, "claim_specificity"), case_id=case.id if case else None, experiment_id=experiment_id,
        kind="deterministic_derivation", status=spec_res["status"],
        title=f"{pref}Claim specificity: does the claim/report persist when the document did not cause the answer?",
        statement=(f"Tested proposition: the claim and the 'document' report are specific to document-caused answers. "
                   f"Non-document-caused branches evaluated: {sorted(inc_rows) or 'none'}. " + " ".join(
                       f"{b}: claim containment {r['claim']['containment']} (re-emitted ≥ {CLAIM_MATCH_THRESHOLD}: "
                       f"{r['claim_persists']}), letter readout 'document' in {r['report_document_orders']}/"
                       f"{r['report_orders']} label orders ({r['reason']})." for b, r in inc_rows.items())
                   + f" Decision: {spec_res['reason']}."),
        measurement={"claim_specificity": spec_res}, scope=sc_, trial_ids=[t.id for t in trials],
        analysis=f"neuralscope.selflab.templates.source_influence:claim_specificity@{ANALYSIS_VERSION}",
        supports=(["claim_specificity"] if spec_res["status"] == "supported" else []),
        contradicts=(["claim_specificity"] if spec_res["status"] == "contradicted" else []),
        limitations=lims + ["Claim re-emission is a word-set containment heuristic (threshold 0.8), not a semantic "
                            "judgement; the measure is reported per branch.",
                            "Branch inclusion for hint_added/document_replaced compares parsed values when a value set "
                            "is known, else the first sentence's word set."], created_at=created))
    ev.append(EvidenceItem(
        id=_ev_id(experiment_id, "reports"), case_id=case.id if case else None, experiment_id=experiment_id,
        kind="model_report", status="untested", title=f"{pref}Constrained source reports per branch",
        statement="Letter-readout categories per branch (two label orders): " + "; ".join(
            f"{b}: {r['letter']} (mass {r['mass']})" for b, r in reports.items()) + ". Reports are model outputs, "
            "not evidence of their own accuracy.",
        measurement={"reports": reports}, scope=sc_, trial_ids=[t.id for t in trials], limitations=lims,
        analysis=f"neuralscope.selflab.templates.source_influence:analyze_case@{ANALYSIS_VERSION}", created_at=created))
    if rp is not None and (rp.measurements.get("patching") or {}).get("defined"):
        pm = rp.measurements["patching"]
        ev.append(EvidenceItem(
            id=_ev_id(experiment_id, "patch"), case_id=case.id if case else None, experiment_id=experiment_id,
            kind="deterministic_derivation", status="untested", title=f"{pref}Residual patching original→replaced "
            f"({PATCH_NOTE})", statement=f"Patching summary: {pm.get('summary')}. Exploratory; no pre-registered "
            "threshold.", measurement={k: pm.get(k) for k in ("summary", "ld_clean", "ld_corrupt", "positions",
                                                               "depths", "restoration", "restoration_joint")},
            scope=sc_, trial_ids=[rp.id], run_ids=list(rp.run_ids) + (list(o.run_ids) if o else []),
            limitations=lims + [PATCH_NOTE], analysis=f"neuralscope.selflab.templates.source_influence:"
            f"analyze_case@{ANALYSIS_VERSION}", created_at=created))
    summary = {"analysis_version": ANALYSIS_VERSION, "template": "source_influence_case", "claim_status": status,
               "reasons": reasons, "delta_response_loglik": d_ll, "reports": reports, "is_fixture": is_demo,
               "claim_specificity": spec_res,
               "model_id": model_id}
    return AnalysisResult(summary=summary, evidence=ev, analysis_version=ANALYSIS_VERSION)


