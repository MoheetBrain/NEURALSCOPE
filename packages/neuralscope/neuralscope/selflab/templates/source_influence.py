    bootstrap_B: int = Field(2000, ge=200, le=20000)
    n_permutations: int = Field(10000, ge=500, le=200000)
    alpha: float = Field(0.05, gt=0.0, lt=0.5)

    @field_validator("conditions")
    @classmethod
    def _conds(cls, v: list[str]) -> list[str]:
        bad = [c for c in v if c not in sc.CONDITIONS]
        if bad or not v:
            raise ValueError(f"unknown/empty conditions {bad}; allowed {list(sc.CONDITIONS)}")
        return [c for c in sc.CONDITIONS if c in v]  # canonical order, no duplicates

    @field_validator("families", "heldout_families")
    @classmethod
    def _fams(cls, v: list[str] | None) -> list[str] | None:
        if v is None:
            return v
        bad = [f for f in v if f not in sc.FAMILIES]
        if bad:
            raise ValueError(f"unknown families {bad}; allowed {list(sc.FAMILIES)}")
        return sorted(set(v))


