    report_max_new_tokens: int = Field(24, ge=1, le=24)
    lab_run_max_new_tokens: int = Field(8, ge=1, le=16)
    # ---- pre-registered controls and analysis settings (part of the hashed spec)
    manipulation_check_min_accuracy: float = Field(0.8, ge=0.0, le=1.0,
                                                   description="doc_v answers must equal the document value at "
                                                               "least this often, else causal labels are unreliable")
    min_option_mass: float = Field(0.5, ge=0.0, le=1.0,
                                   description="mean probability mass on the 4 option letters; below → the letter "
                                               "readout is not where the model puts its weight")
