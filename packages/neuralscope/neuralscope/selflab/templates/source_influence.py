def allowed_families(split: str, p: BatteryParams) -> list[str]:
    """Split policy: debug_pilot/discovery exclude held-out families; heldout_confirmation uses only them."""
    held = tuple(p.heldout_families)
    if split == "heldout_confirmation":
        fams = [f for f in sc.FAMILIES if f in held]
    elif split in ("discovery", "debug_pilot"):
        fams = [f for f in sc.FAMILIES if f not in held]
    else:
        raise ValueError(f"unknown split {split!r}")
    if p.families is not None:
        fams = [f for f in fams if f in p.families]
    if not fams:
        raise ValueError(f"no families left for split {split!r} (families={p.families}, heldout={list(held)})")
    return fams


